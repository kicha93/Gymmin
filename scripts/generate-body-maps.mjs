import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "scripts", "anatomy-source");
const outputPath = path.join(root, "apps", "mobile", "src", "domain", "bodySvg.generated.ts");

const sources = {
  frontBodySvg: {
    file: "body-front-standard.svg",
    viewBox: "0 0 969 1624"
  },
  backBodySvg: {
    file: "body-back-standard.svg",
    viewBox: "0 0 964 1632"
  },
  advancedFrontBodySvg: {
    file: "body-front-subgroups.svg",
    viewBox: "0 -4 969 1632"
  },
  advancedBackBodySvg: {
    file: "body-back-subgroups.svg",
    viewBox: "-2.5 0 969 1632"
  }
};

const outputs = [];
for (const [exportName, config] of Object.entries(sources)) {
  const raw = await readFile(path.join(sourceDir, config.file), "utf8");
  const normalized = normalizeSvg(raw, config.viewBox);
  validateSvg(normalized, config.file);
  outputs.push(`export const ${exportName} = ${JSON.stringify(normalized)};`);
}

const generated = `// Generated by scripts/generate-body-maps.mjs. Do not edit manually.\n${outputs.join("\n\n")}\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error(`${path.relative(root, outputPath)} is stale; run node scripts/generate-body-maps.mjs`);
  }
  console.log(`Verified ${path.relative(root, outputPath)}`);
  process.exit(0);
}

await writeFile(outputPath, generated, "utf8");

console.log(`Generated ${path.relative(root, outputPath)}`);

function normalizeSvg(svg, viewBox) {
  return svg
    .replace(/^\uFEFF/, "")
    .replace(/<\?xml[\s\S]*?\?>/gi, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<metadata\b[\s\S]*?<\/metadata>/gi, "")
    .replace(/<title\b[\s\S]*?<\/title>/gi, "")
    .replace(/\s(?:aria-label|role|class|data-[\w-]+)="[^"]*"/gi, "")
    .replace(/\s(?:pointer-events|vector-effect)="[^"]*"/gi, "")
    .replace(/\sxmlns:ns\d+="[^"]*"/g, "")
    .replace(/(<\/?)(?:ns\d+:)/g, "$1")
    .replace(/\sviewBox="[^"]*"/, ` viewBox="${viewBox}"`)
    .replace(/<svg\b[^>]*>/, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" preserveAspectRatio="xMidYMid meet">`)
    .replace(/>\s+</g, "><")
    .trim();
}

function validateSvg(svg, file) {
  if (!svg.startsWith("<svg") || !svg.endsWith("</svg>")) {
    throw new Error(`${file}: invalid SVG root`);
  }
  if (/<\/?ns\d+:/.test(svg)) {
    throw new Error(`${file}: namespace-prefixed tags remain`);
  }
  const ids = [...svg.matchAll(/(?:^|\s)id="([^"]+)"/g)].map((match) => match[1]);
  const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index);
  if (duplicates.length > 0) {
    throw new Error(`${file}: duplicate IDs: ${[...new Set(duplicates)].join(", ")}`);
  }
}
