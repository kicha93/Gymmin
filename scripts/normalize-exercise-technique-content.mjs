import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, "apps", "mobile", "src", "domain", "exerciseTechniqueContent.ts");
const source = fs.readFileSync(target, "utf8");
const marker = "export const exerciseTechniqueContentById";

if (!source.includes(marker)) {
  console.log("Exercise technique content is already normalized.");
  process.exit(0);
}

const objectStart = source.indexOf("{", source.indexOf(marker));
const objectEnd = source.indexOf("\n};", objectStart);
if (objectStart < 0 || objectEnd < 0) {
  throw new Error("Could not locate the legacy exercise technique content object.");
}

const records = JSON.parse(source.slice(objectStart, objectEnd + 2));
const localizedTexts = [];
const localizedTextIndex = new Map();
const templates = [];
const templateIndex = new Map();
const exerciseTemplates = {};

function internText(value) {
  const key = JSON.stringify([value.pl, value.en]);
  const existing = localizedTextIndex.get(key);
  if (existing !== undefined) return existing;
  const index = localizedTexts.length;
  localizedTexts.push([value.pl, value.en]);
  localizedTextIndex.set(key, index);
  return index;
}

for (const [exerciseId, content] of Object.entries(records)) {
  const template = [
    content.instructions.map(internText),
    content.techniqueTips.map(internText),
    content.commonMistakes.map(internText)
  ];
  const key = JSON.stringify(template);
  let index = templateIndex.get(key);
  if (index === undefined) {
    index = templates.length;
    templates.push(template);
    templateIndex.set(key, index);
  }
  exerciseTemplates[exerciseId] = index;
}

const output = `import { resolveExerciseId } from "./exercises";

export type LocalizedExerciseText = {
  pl: string;
  en: string;
};

export type ExerciseTechniqueContent = {
  instructions: LocalizedExerciseText[];
  techniqueTips: LocalizedExerciseText[];
  commonMistakes: LocalizedExerciseText[];
};

type TechniqueTemplate = readonly [
  instructions: readonly number[],
  techniqueTips: readonly number[],
  commonMistakes: readonly number[]
];

// Generated by scripts/normalize-exercise-technique-content.mjs.
// Repeated localized paragraphs and full technique sets are interned to keep
// Metro parsing, TypeScript analysis and application startup bounded.
const localizedTexts: readonly (readonly [pl: string, en: string])[] = ${JSON.stringify(localizedTexts)};
const techniqueTemplates: readonly TechniqueTemplate[] = ${JSON.stringify(templates)};
const techniqueTemplateIndexByExerciseId: Readonly<Record<string, number>> = ${JSON.stringify(exerciseTemplates)};
const expandedContentCache = new Map<string, ExerciseTechniqueContent>();

export function getExerciseTechniqueContent(exerciseId: string): ExerciseTechniqueContent | undefined {
  const canonicalId = resolveExerciseId(exerciseId);
  const cached = expandedContentCache.get(canonicalId);
  if (cached) {
    return cached;
  }

  const templateIndex = techniqueTemplateIndexByExerciseId[canonicalId];
  const template = templateIndex === undefined ? undefined : techniqueTemplates[templateIndex];
  if (!template) {
    return undefined;
  }

  const content: ExerciseTechniqueContent = {
    instructions: expandLocalizedTexts(template[0]),
    techniqueTips: expandLocalizedTexts(template[1]),
    commonMistakes: expandLocalizedTexts(template[2])
  };
  expandedContentCache.set(canonicalId, content);
  return content;
}

function expandLocalizedTexts(indexes: readonly number[]): LocalizedExerciseText[] {
  return indexes.map((index) => {
    const [pl, en] = localizedTexts[index];
    return { pl, en };
  });
}
`;

fs.writeFileSync(target, output, "utf8");
console.log(JSON.stringify({
  exercises: Object.keys(records).length,
  localizedTexts: localizedTexts.length,
  templates: templates.length
}, null, 2));
